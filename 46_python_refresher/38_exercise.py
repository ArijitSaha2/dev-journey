# Exercise 38 — While Loops
# Write a program that:
# 1. Starts with a variable number = 1.
# 2. Uses a while loop to print numbers from 1 to 10.
# 3. Increments the number after each iteration.
# 4. Stops when the number exceeds 10.

def while_loop(V):
    while V <= 10:
        print(V)
        V += 1

while_loop(V = 1)